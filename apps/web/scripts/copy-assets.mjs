#!/usr/bin/env node
// Copies generated public assets before `next dev` / `next build` (never hand-edit the copies):
//  - brand/*.svg (canonical at the repo root) → public/brand/
//  - brand/favicon.svg → public/favicon.svg
//  - @mediabunny/aac-encoder's bundle, unmodified, → public/vendor/aac-encoder-<version>.mjs
//    (LGPL-2.1 FFmpeg AAC encoder inlined as WASM; loaded lazily as a separate, replaceable file.)
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..');
const brand = resolve(app, '../../brand');
const pub = join(app, 'public');

mkdirSync(join(pub, 'brand'), { recursive: true });
for (const f of readdirSync(brand)) {
  if (f.endsWith('.svg')) copyFileSync(join(brand, f), join(pub, 'brand', f));
}
copyFileSync(join(brand, 'favicon.svg'), join(pub, 'favicon.svg'));

const aacPkgPath = join(app, 'node_modules/@mediabunny/aac-encoder/package.json');
const aacPkg = JSON.parse(readFileSync(aacPkgPath, 'utf8'));
const src = join(dirname(aacPkgPath), 'dist/bundles/mediabunny-aac-encoder.min.mjs');
mkdirSync(join(pub, 'vendor'), { recursive: true });
const name = `aac-encoder-${aacPkg.version}.mjs`;
copyFileSync(src, join(pub, 'vendor', name));
writeFileSync(
  join(app, 'src/config/vendor.generated.ts'),
  `// Generated by scripts/copy-assets.mjs. Do not edit.\nexport const AAC_ENCODER_URL = '/vendor/${name}';\nexport const AAC_ENCODER_VERSION = '${aacPkg.version}';\n`,
);
mkdirSync(join(pub, 'fonts'), { recursive: true });
for (const [pkg, file] of [
  ['outfit', 'outfit-latin-wght-normal.woff2'],
  ['atkinson-hyperlegible-next', 'atkinson-hyperlegible-next-latin-wght-normal.woff2'],
  ['jetbrains-mono', 'jetbrains-mono-latin-wght-normal.woff2'],
]) {
  copyFileSync(join(app, 'node_modules/@fontsource-variable', pkg, 'files', file), join(pub, 'fonts', file));
}
// Destination glyphs: brand/glyphs/*.svg stay canonical; inline their inner markup for React.
const glyphs = {};
for (const f of readdirSync(join(brand, 'glyphs')).sort()) {
  if (!f.endsWith('.svg')) continue;
  const svg = readFileSync(join(brand, 'glyphs', f), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
  glyphs[f.replace(/\.svg$/, '')] = inner;
}
writeFileSync(
  join(app, 'src/components/glyphs.generated.ts'),
  `// Generated by scripts/copy-assets.mjs from brand/glyphs/*.svg. Do not edit.\nexport const DESTINATION_GLYPHS = ${JSON.stringify(glyphs, null, 2)} as const;\nexport type DestinationGlyph = keyof typeof DESTINATION_GLYPHS;\n`,
);
console.log(`copy-assets: glyphs, fonts → public/fonts, brand → public/brand, ${name} → public/vendor`);
